#!/usr/bin/env python3
"""Derive the fork's CI workflows from upstream's.

Upstream's workflow files stay on ai2-main unchanged and are disabled on the
fork through the GitHub API. Each workflow in ALLOWLIST is copied to
.github/workflows/ai2-<name>.yaml with its triggers replaced, so the copy runs
only on pushes to ai2-main and on pull requests that target it. The jobs are
upstream's, unchanged.

The copies are re-derived from upstream rather than carried as patches, so
upstream changes to the jobs reach the fork on every sync:

    python3 ai2/derive_workflows.py                               # write the copies
    python3 ai2/derive_workflows.py --check                       # exit 1 if stale
    python3 ai2/derive_workflows.py --disable-upstream --dry-run  # list, change nothing
    python3 ai2/derive_workflows.py --disable-upstream            # disable on GitHub
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from pathlib import Path

from check_modified_notices import GitError, comment_line, git, resolve_upstream

FORK_BRANCH = "ai2-main"
WORKFLOW_DIR = ".github/workflows"
COPY_PREFIX = "ai2-"
# `.yaml`, not `.yml`: upstream tests inventory `*.yml` in this directory, and
# the copies are not upstream's to classify.
COPY_SUFFIX = ".yaml"
GENERATED_MARKER = "Generated by ai2/derive_workflows.py"

PUSH_AND_PULL_REQUEST = ("pull_request", "push")

# Upstream workflow -> the events its copy runs on.
ALLOWLIST: dict[str, tuple[str, ...]] = {
    "ci.yml": PUSH_AND_PULL_REQUEST,
    "lint.yml": PUSH_AND_PULL_REQUEST,
    "web-tests.yml": PUSH_AND_PULL_REQUEST,
    "integration.yml": PUSH_AND_PULL_REQUEST,
    "e2e.yml": PUSH_AND_PULL_REQUEST,
    "docker-build.yml": PUSH_AND_PULL_REQUEST,
    "windows.yml": PUSH_AND_PULL_REQUEST,
    "kustomize-validate.yml": PUSH_AND_PULL_REQUEST,
    "trivy.yml": PUSH_AND_PULL_REQUEST,
    # The security gate only waits on this scan for pull requests.
    "security-scan.yml": ("pull_request",),
}

# Both events take their filters from upstream's pull_request trigger. Branch
# filters are replaced. An unknown key stops the script for a human decision.
KNOWN_FILTERS = frozenset({"types", "branches", "branches-ignore", "paths", "paths-ignore"})
KEPT_FILTERS: dict[str, frozenset[str]] = {
    "pull_request": frozenset({"types", "paths", "paths-ignore"}),
    "push": frozenset({"paths", "paths-ignore"}),
}

ON_LINE = re.compile(r"^on:\s*(#.*)?$")
INLINE_REUSABLE_ON = re.compile(r"(?m)^on:\s*\[?\s*workflow_call\s*\]?\s*(#.*)?$")
EVENT_LINE = re.compile(r"^  ([A-Za-z_]+):\s*(.*?)\s*$")
FILTER_LINE = re.compile(r"^    ([A-Za-z_-]+):")
GITHUB_REMOTE = re.compile(r"github\.com[:/]([^/]+/[^/]+?)(?:\.git)?/?$")


class DeriveError(RuntimeError):
    """Raised when an upstream workflow cannot be derived mechanically."""


def indent_of(line: str) -> int:
    return len(line) - len(line.lstrip(" "))


def copy_name(upstream_name: str) -> str:
    return f"{COPY_PREFIX}{Path(upstream_name).stem}{COPY_SUFFIX}"


def split_triggers(text: str, source: str) -> tuple[str, list[str], str]:
    """Split a workflow into (text before `on:`, trigger lines, text after)."""
    lines = text.splitlines(keepends=True)
    starts = [index for index, line in enumerate(lines) if ON_LINE.match(line)]
    if len(starts) != 1:
        raise DeriveError(f"{source}: expected one top-level 'on:' block, found {len(starts)}")
    start = starts[0]
    end = start + 1
    while end < len(lines) and (not lines[end].strip() or lines[end][0] in " #"):
        end += 1
    # Blank lines and column-0 comments just above the next key belong to it.
    while end > start + 1 and (not lines[end - 1].strip() or lines[end - 1].startswith("#")):
        end -= 1
    return "".join(lines[:start]), lines[start + 1 : end], "".join(lines[end:])


def event_bodies(block: list[str], source: str) -> dict[str, list[str]]:
    """Map each trigger event to the indented lines beneath it."""
    events: dict[str, list[str]] = {}
    current: list[str] | None = None
    for line in block:
        if not line.strip():
            continue
        match = EVENT_LINE.match(line)
        if match:
            name, inline = match.groups()
            if inline and not inline.startswith("#"):
                raise DeriveError(f"{source}: inline value for trigger '{name}' is not supported")
            current = events.setdefault(name, [])
        elif indent_of(line) >= 4 and current is not None:
            current.append(line)
        elif line.lstrip().startswith("#"):
            current = None
        else:
            raise DeriveError(f"{source}: cannot parse trigger line: {line.strip()}")
    return events


def split_filters(body: list[str], source: str) -> list[tuple[str, list[str]]]:
    """Split an event body into (filter key, lines), keeping each key's comments."""
    filters: list[tuple[str, list[str]]] = []
    pending_comments: list[str] = []
    for line in body:
        match = FILTER_LINE.match(line)
        if match:
            filters.append((match.group(1), [*pending_comments, line]))
            pending_comments = []
        elif indent_of(line) == 4 and line.lstrip().startswith("#"):
            pending_comments.append(line)
        elif filters and indent_of(line) > 4:
            filters[-1][1].append(line)
        else:
            raise DeriveError(f"{source}: cannot parse trigger filter line: {line.strip()}")
    return filters


def derive_copy(upstream_name: str, text: str) -> str:
    """Return the fork copy of one upstream workflow."""
    before, block, after = split_triggers(text, upstream_name)
    bodies = event_bodies(block, upstream_name)
    if "pull_request" not in bodies:
        raise DeriveError(f"{upstream_name}: no pull_request trigger to take filters from")
    filters = split_filters(bodies["pull_request"], upstream_name)
    unknown = sorted({key for key, _ in filters} - KNOWN_FILTERS)
    if unknown:
        raise DeriveError(f"{upstream_name}: unsupported pull_request filter(s): {', '.join(unknown)}")

    triggers = ["on:\n"]
    for event in ALLOWLIST[upstream_name]:
        triggers.append(f"  {event}:\n")
        triggers.append(f"    branches: [{FORK_BRANCH}]\n")
        for key, lines in filters:
            if key in KEPT_FILTERS[event]:
                triggers.extend(lines)

    copy_path = f"{WORKFLOW_DIR}/{copy_name(upstream_name)}"
    body = before + "".join(triggers) + after
    # Self-references (path filters, scope scripts) must name the copy.
    body = re.sub(re.escape(f"{WORKFLOW_DIR}/{upstream_name}") + r"(?![\w.-])", copy_path, body)
    header = (
        f"{comment_line(copy_path)}\n"
        f"# {GENERATED_MARKER} from {WORKFLOW_DIR}/{upstream_name}.\n"
        "# The jobs are upstream's; only the triggers differ. Re-run the script, do not edit.\n"
    )
    return header + body


def upstream_base(explicit: str | None) -> str:
    """The upstream commit HEAD is built on, so copies match HEAD's upstream."""
    return git("merge-base", "HEAD", resolve_upstream(explicit)).strip()


def read_at(ref: str, path: str) -> str:
    return git("show", f"{ref}:{path}")


def desired_copies(base: str) -> dict[str, str]:
    return {
        copy_name(name): derive_copy(name, read_at(base, f"{WORKFLOW_DIR}/{name}"))
        for name in ALLOWLIST
    }


def generated_files(directory: Path) -> list[Path]:
    """Copies this script wrote earlier, including ones no longer allowlisted."""
    if not directory.is_dir():
        return []
    return sorted(
        path
        for path in directory.glob(f"{COPY_PREFIX}*")
        if path.is_file() and GENERATED_MARKER in path.read_text(encoding="utf-8")
    )


def sync_copies(directory: Path, desired: dict[str, str], check: bool) -> list[str]:
    """Write or verify the copies; return the names that were (or would be) changed."""
    changed: list[str] = []
    for name, content in sorted(desired.items()):
        path = directory / name
        current = path.read_text(encoding="utf-8") if path.is_file() else None
        if current != content:
            changed.append(name)
            if not check:
                path.write_text(content, encoding="utf-8")
    for path in generated_files(directory):
        if path.name not in desired:
            changed.append(path.name)
            if not check:
                path.unlink()
    return changed


def is_reusable_only(text: str) -> bool:
    """True when a workflow runs only when another workflow calls it."""
    try:
        _, block, _ = split_triggers(text, "workflow")
        return set(event_bodies(block, "workflow")) == {"workflow_call"}
    except DeriveError:
        return bool(INLINE_REUSABLE_ON.search(text))


def fork_slug() -> str:
    url = git("remote", "get-url", "origin").strip()
    match = GITHUB_REMOTE.search(url)
    if not match:
        raise DeriveError(f"origin is not a GitHub remote: {url}")
    return match.group(1)


def gh_api(*args: str) -> str:
    result = subprocess.run(["gh", "api", *args], capture_output=True, text=True, check=False)
    if result.returncode != 0:
        raise DeriveError(f"gh api {' '.join(args)}: {result.stderr.strip()}")
    return result.stdout


def disable_upstream(base: str, dry_run: bool) -> int:
    """Disable every active upstream workflow on the fork, except reusable ones."""
    slug = fork_slug()
    raw = gh_api(
        "--paginate",
        f"repos/{slug}/actions/workflows",
        "--jq",
        ".workflows[] | {id, path, state}",
    )
    workflows = [json.loads(line) for line in raw.splitlines() if line.strip()]
    targets = []
    for workflow in workflows:
        path = workflow["path"]
        if not path.startswith(f"{WORKFLOW_DIR}/") or Path(path).name.startswith(COPY_PREFIX):
            continue
        if workflow["state"] != "active":
            continue
        try:
            text = read_at(base, path)
        except GitError:
            text = ""
        if text and is_reusable_only(text):
            continue
        targets.append(workflow)

    verb = "would disable" if dry_run else "disabling"
    print(f"{slug}: {len(workflows)} workflows registered, {verb} {len(targets)}")
    for workflow in targets:
        print(f"  {workflow['path']}")
        if not dry_run:
            gh_api("-X", "PUT", f"repos/{slug}/actions/workflows/{workflow['id']}/disable")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument(
        "--upstream",
        default=None,
        help="upstream ref; the copies derive from its merge base with HEAD",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit non-zero if a copy is missing or stale; write nothing",
    )
    parser.add_argument(
        "--disable-upstream",
        action="store_true",
        help="disable upstream's workflows on the fork through the GitHub API",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="with --disable-upstream: list the workflows, change nothing",
    )
    args = parser.parse_args()

    try:
        base = upstream_base(args.upstream)
        if args.disable_upstream:
            return disable_upstream(base, args.dry_run)
        root = Path(git("rev-parse", "--show-toplevel").strip())
        directory = root / WORKFLOW_DIR
        changed = sync_copies(directory, desired_copies(base), args.check)
    except (DeriveError, GitError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2

    if not changed:
        print(f"{WORKFLOW_DIR}: {len(ALLOWLIST)} workflow copies are current")
        return 0
    if args.check:
        print(
            f"error: workflow copies are stale: {', '.join(changed)}. "
            "Run: python3 ai2/derive_workflows.py",
            file=sys.stderr,
        )
        return 1
    print(f"{WORKFLOW_DIR}: updated {', '.join(changed)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
